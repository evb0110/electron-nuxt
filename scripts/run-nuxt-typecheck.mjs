import { spawn } from 'node:child_process';
import {
    readFileSync,
    writeFileSync,
    existsSync,
} from 'node:fs';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';

const require = createRequire(import.meta.url);

// Keep vue-tsc pinned in the workspace so CI and local runs share the same
// typecheck toolchain instead of npm fetching a newer transient version.
require.resolve('vue-tsc/package.json');

const workspaceDir = process.argv[2] ? resolve(process.argv[2]) : process.cwd();
const env = {
    ...process.env,
    NODE_ENV: process.env.NODE_ENV || 'production', 
};

// pnpm injects npm-specific config vars that newer npm versions warn about when
// Nuxt shells out through npm internals.
for (const key of Object.keys(env)) {
    if (!key.startsWith('npm_config_')) continue;
    if (key === 'npm_config_user_agent') continue;
    delete env[key];
}

function runChild(command, args) {
    return new Promise((resolveRun, rejectRun) => {
        const child = spawn(command, args, {
            cwd: workspaceDir,
            env,
            stdio: 'inherit',
        });
        child.on('exit', (code, signal) => {
            if (signal) {
                process.kill(process.pid, signal);
                return;
            }
            if (code && code !== 0) {
                rejectRun(new Error(`${command} ${args.join(' ')} exited with code ${code}`));
                return;
            }
            resolveRun();
        });
        child.on('error', rejectRun);
    });
}

// Strip the v5-only `vue-router/volar/sfc-route-blocks` plugin entry.
// Top-level vue-router is pinned to v4 (required by @nuxt/ui); Nuxt's pages module
// unconditionally pushes this plugin into vueCompilerOptions.plugins. vue-tsc resolves
// it through the hoisted v4 -> ERR_PACKAGE_PATH_NOT_EXPORTED warning every run.
function stripVolarRouterPlugin(tsConfigLike) {
    const compilerOptions = tsConfigLike?.vueCompilerOptions;
    if (!compilerOptions || !Array.isArray(compilerOptions.plugins)) {
        return;
    }
    compilerOptions.plugins = compilerOptions.plugins.filter(
        plugin => plugin !== 'vue-router/volar/sfc-route-blocks',
    );
}

function stripVolarRouterPluginOnDisk(tsconfigPath) {
    if (!existsSync(tsconfigPath)) {
        return;
    }
    const raw = readFileSync(tsconfigPath, 'utf-8');
    let parsed;
    try { parsed = JSON.parse(raw); } catch { return; }
    const before = parsed?.vueCompilerOptions?.plugins?.length ?? 0;
    stripVolarRouterPlugin(parsed);
    const after = parsed?.vueCompilerOptions?.plugins?.length ?? 0;
    if (before !== after) {
        writeFileSync(tsconfigPath, `${JSON.stringify(parsed, null, 2)}\n`);
    }
}

async function prepareWithKit() {
    // Equivalent to `nuxt prepare` but programmatic — guarantees no orphan writer
    // continues after our function returns, so subsequent on-disk patches stick.
    // @nuxt/kit isn't a direct dep — resolve through nuxt's own dep tree, mirroring
    // how the official `nuxt typecheck` command (which lives in @nuxt/cli) does it.
    const nuxtPackageJsonPath = require.resolve('nuxt/package.json');
    const kitModulePath = require.resolve('@nuxt/kit', { paths: [nuxtPackageJsonPath] });
    const kit = await import(kitModulePath);
    const {
        loadNuxt,
        buildNuxt,
        writeTypes,
    } = kit;
    const nuxt = await loadNuxt({
        cwd: workspaceDir,
        overrides: {
            _prepare: true,
            logLevel: 'silent', 
        },
    });
    // Register a final-position hook that strips the plugin from the in-memory tsConfig
    // before Nuxt writes it to disk.
    nuxt.hook('prepare:types', ({ tsConfig }) => stripVolarRouterPlugin(tsConfig));
    try {
        await writeTypes(nuxt);
        await buildNuxt(nuxt);
    } finally {
        await nuxt.close();
    }
}

async function main() {
    await prepareWithKit();

    // Defensive on-disk patch in case any tsconfig leaked through (e.g. tsconfig.app.json
    // generated by a different code path that doesn't go through `prepare:types`).
    for (const candidate of [
        resolve(workspaceDir, '.nuxt/tsconfig.json'),
        resolve(workspaceDir, '.nuxt/tsconfig.app.json'),
        resolve(workspaceDir, '.nuxt/tsconfig.node.json'),
    ]) {
        stripVolarRouterPluginOnDisk(candidate);
    }

    const vueTscBin = require.resolve('vue-tsc/bin/vue-tsc.js');
    await runChild(process.execPath, [
        vueTscBin,
        '--noEmit',
    ]);
}

main().catch((error) => {
    console.error(error?.message || error);
    process.exit(1);
});
